#!/usr/bin/env python3
"""Project knowledge graph: index-based memory that points to exact `path:line` answers.

Nodes live in .claude/knowledge/nodes/<id>.md (frontmatter + short facts with pointers).
`index` regenerates INDEX.md (the entry point) and graph.json (typed edges).

Commands: index | query | show | neighbors | upsert | remove | prune | validate | stale | pending | seed | stats
See docs in .claude/skills/knowledge-graph/SKILL.md.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import fnmatch
import json
import os
import re
import subprocess
import sys
from collections import defaultdict, deque
from typing import Dict, List, Optional, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
KINDS = ["architecture", "module", "entrypoint", "api", "data-model", "workflow", "command",
         "decision", "gotcha", "doc", "glossary"]
KIND_TITLES = {"architecture": "Architecture", "module": "Modules", "entrypoint": "Entry points", "api": "APIs",
               "data-model": "Data models", "workflow": "Workflows", "command": "Commands",
               "decision": "Decisions", "gotcha": "Gotchas", "doc": "Docs", "glossary": "Glossary"}
EDGE_TYPES = {"depends_on", "implements", "calls", "documented_in", "decided_by", "related"}
ID_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
SOURCE_RE = re.compile(r"^(?P<path>[^:]+?)(?::(?P<a>\d+)(?:-(?P<b>\d+))?)?$")
FIELD_ORDER = ["id", "kind", "title", "summary", "tags", "links", "sources", "updated", "verified_commit"]
GENERATED_MARK = "<!-- generated by .claude/tools/kg.py index; do not edit by hand -->"


# ------------------------------------------------------------------ paths/config

def project_root(explicit: Optional[str] = None) -> str:
    if explicit:
        return os.path.abspath(explicit)
    env = os.environ.get("CLAUDE_PROJECT_DIR")
    if env:
        return env
    return os.path.abspath(os.path.join(HERE, "..", ".."))


class KG:
    def __init__(self, root: str):
        self.root = root
        self.kdir = os.path.join(root, ".claude", "knowledge")
        self.ndir = os.path.join(self.kdir, "nodes")
        self.index_path = os.path.join(self.kdir, "INDEX.md")
        self.graph_path = os.path.join(self.kdir, "graph.json")
        self.pending_path = os.path.join(root, ".claude", "state", "kg-pending")
        cfg = {}
        try:
            with open(os.path.join(root, ".claude", "harness.json"), encoding="utf-8") as fh:
                cfg = json.load(fh).get("knowledge", {})
        except (OSError, ValueError):
            pass
        self.max_index_lines = int(cfg.get("max_index_lines", 200))
        self.max_node_lines = int(cfg.get("max_node_lines", 60))
        self.ignore = cfg.get("ignore", ["tests/**", "test/**", "**/*.test.*", "**/*.spec.*", ".claude/**"])

    # -------------------------------------------------------------- node io
    def node_files(self) -> List[str]:
        if not os.path.isdir(self.ndir):
            return []
        return sorted(os.path.join(self.ndir, f) for f in os.listdir(self.ndir) if f.endswith(".md"))

    def load(self) -> List[Dict]:
        return [n for n in (parse_node(p) for p in self.node_files()) if n]

    def by_id(self) -> Dict[str, Dict]:
        return {n["meta"].get("id", ""): n for n in self.load()}


# ------------------------------------------------------------------ frontmatter

def _parse_value(v: str):
    v = v.strip()
    if v.startswith("[") and v.endswith("]"):
        inner = v[1:-1].strip()
        return [x.strip().strip("'\"") for x in inner.split(",") if x.strip()] if inner else []
    return v.strip("'\"")


def parse_node(path: str) -> Optional[Dict]:
    try:
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
    except OSError:
        return None
    return parse_node_text(text, path)


def parse_node_text(text: str, path: str = "") -> Dict:
    meta: Dict = {}
    body = text
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            fm = text[3:end].strip("\n")
            body = text[end + 4:].lstrip("\n")
            key = None
            for line in fm.splitlines():
                if re.match(r"^\s+-\s+", line) and key:  # tolerate block lists
                    meta.setdefault(key, [])
                    if isinstance(meta[key], list):
                        meta[key].append(line.split("-", 1)[1].strip().strip("'\""))
                    continue
                if ":" in line:
                    key, val = line.split(":", 1)
                    key = key.strip()
                    meta[key] = _parse_value(val) if val.strip() else []
    for k in ("tags", "links", "sources"):
        if isinstance(meta.get(k), str):
            meta[k] = [meta[k]] if meta[k] else []
        meta.setdefault(k, [])
    return {"meta": meta, "body": body, "file": path}


def dump_node(meta: Dict, body: str) -> str:
    lines = ["---"]
    keys = FIELD_ORDER + [k for k in meta if k not in FIELD_ORDER]
    for k in keys:
        if k not in meta:
            continue
        v = meta[k]
        lines.append(f"{k}: [{', '.join(v)}]" if isinstance(v, list) else f"{k}: {v}")
    lines.append("---")
    return "\n".join(lines) + "\n" + body.rstrip("\n") + "\n"


def parse_link(link: str) -> Tuple[str, str]:
    if ":" in link:
        t, target = link.split(":", 1)
        if t in EDGE_TYPES:
            return t, target
    return "related", link


def parse_source(src: str) -> Optional[Tuple[str, Optional[int], Optional[int]]]:
    m = SOURCE_RE.match(src.strip())
    if not m:
        return None
    a = int(m.group("a")) if m.group("a") else None
    b = int(m.group("b")) if m.group("b") else a
    return m.group("path"), a, b


def today() -> str:
    return _dt.date.today().isoformat()


def git(root: str, *args: str, timeout: int = 10) -> Optional[str]:
    try:
        r = subprocess.run(["git", "-C", root, *args], capture_output=True, text=True, timeout=timeout)
        return r.stdout.strip() if r.returncode == 0 else None
    except (OSError, subprocess.TimeoutExpired):
        return None


def head_commit(root: str) -> str:
    return git(root, "rev-parse", "--short", "HEAD") or "none"


# ------------------------------------------------------------------ index

def build_index(kg: KG) -> Tuple[str, Dict]:
    nodes = kg.load()
    by_kind: Dict[str, List[Dict]] = defaultdict(list)
    for n in nodes:
        by_kind[n["meta"].get("kind", "glossary")].append(n)
    kinds = [k for k in KINDS if by_kind.get(k)] + sorted(k for k in by_kind if k not in KINDS)

    header = [
        "# Knowledge Index",
        GENERATED_MARK,
        "",
        "**How to use:** find the topic below → open the node file → jump to the `path:line` pointer with a ranged Read.",
        "Search: `python3 .claude/tools/kg.py query <terms>` · Related: `kg.py neighbors <id>` · Update: knowledge-keeper agent.",
        "",
        f"Nodes: {len(nodes)}",
    ]
    sections: List[Tuple[str, List[str]]] = []
    for k in kinds:
        rows = []
        for n in sorted(by_kind[k], key=lambda n: n["meta"].get("id", "")):
            m = n["meta"]
            first_src = m["sources"][0] if m["sources"] else ""
            rel = os.path.relpath(n["file"], kg.kdir).replace(os.sep, "/")
            rows.append(f"- **{m.get('id')}**: {m.get('summary', '')} → `{rel}`" + (f" · `{first_src}`" if first_src else ""))
        sections.append((KIND_TITLES.get(k, k.title()), rows))

    tag_map: Dict[str, List[str]] = defaultdict(list)
    for n in nodes:
        for t in n["meta"]["tags"]:
            tag_map[t.lower()].append(n["meta"].get("id", ""))
    kw_rows = [f"- {t} → {', '.join(sorted(set(ids)))}" for t, ids in sorted(tag_map.items())]

    budget = kg.max_index_lines - len(header) - 2 * len(sections) - 3
    total_rows = sum(len(r) for _, r in sections)
    out = list(header)
    if total_rows > budget > 0:
        per = max(3, budget // max(1, len(sections)))
    else:
        per = None
    for title, rows in sections:
        out += ["", f"## {title}"]
        if per and len(rows) > per:
            out += rows[:per - 1] + [f"- … {len(rows) - per + 1} more (search with `kg.py query`)"]
        else:
            out += rows
    remaining = kg.max_index_lines - len(out) - 2
    if kw_rows and remaining > 2:
        out += ["", "## Keywords"]
        out += kw_rows[:remaining] if len(kw_rows) <= remaining else kw_rows[:remaining - 1] + [
            f"- … {len(kw_rows) - remaining + 1} more keywords (search with `kg.py query`)"]

    graph = {
        "version": 1,
        "nodes": [{"id": n["meta"].get("id"), "kind": n["meta"].get("kind"), "title": n["meta"].get("title", ""),
                   "summary": n["meta"].get("summary", ""), "tags": n["meta"]["tags"],
                   "sources": n["meta"]["sources"],
                   "file": os.path.relpath(n["file"], kg.root).replace(os.sep, "/")} for n in nodes],
        "edges": [{"from": n["meta"].get("id"), "to": parse_link(l)[1], "type": parse_link(l)[0]}
                  for n in nodes for l in n["meta"]["links"]],
    }
    return "\n".join(out) + "\n", graph


def cmd_index(kg: KG, args) -> int:
    os.makedirs(kg.ndir, exist_ok=True)
    text, graph = build_index(kg)
    with open(kg.index_path, "w", encoding="utf-8") as fh:
        fh.write(text)
    with open(kg.graph_path, "w", encoding="utf-8") as fh:
        json.dump(graph, fh, indent=1)
    print(f"INDEX.md: {text.count(chr(10))} lines · {len(graph['nodes'])} nodes · {len(graph['edges'])} edges")
    return 0


# ------------------------------------------------------------------ query/show/neighbors

def _score(n: Dict, terms: List[str]) -> int:
    m = n["meta"]
    s = 0
    idt = m.get("id", "").lower()
    tags = [t.lower() for t in m["tags"]]
    title = (m.get("title", "") or "").lower()
    summ = (m.get("summary", "") or "").lower()
    body = n["body"].lower()
    srcs = " ".join(m["sources"]).lower()
    for t in terms:
        if t in tags:
            s += 6
        if t in idt:
            s += 4
        if t in title:
            s += 3
        if t in summ:
            s += 2
        if t in srcs:
            s += 2
        if t in body:
            s += 1
    return s


def cmd_query(kg: KG, args) -> int:
    terms = [t.lower() for t in args.terms]
    ranked = sorted(((_score(n, terms), n) for n in kg.load()), key=lambda x: -x[0])
    hits = [(s, n) for s, n in ranked if s > 0][: args.limit]
    if not hits:
        print("No KG match. Fall back to Grep/Glob, then record the answer via knowledge-keeper (KG: gap <topic>).")
        return 1
    for s, n in hits:
        m = n["meta"]
        print(f"{m.get('id')} ({m.get('kind')}) score={s}: {m.get('summary', '')}")
        print(f"   node: {os.path.relpath(n['file'], kg.root)}")
        if m["sources"]:
            print(f"   sources: {', '.join(m['sources'][:4])}")
        facts = [l.strip() for l in n["body"].splitlines() if l.strip().startswith("-") and any(t in l.lower() for t in terms)]
        for f in facts[:3]:
            print(f"   {f}")
    return 0


def cmd_show(kg: KG, args) -> int:
    n = kg.by_id().get(args.id)
    if not n:
        print(f"unknown node: {args.id}", file=sys.stderr)
        return 1
    with open(n["file"], encoding="utf-8") as fh:
        print(fh.read())
    return 0


def cmd_neighbors(kg: KG, args) -> int:
    nodes = kg.by_id()
    if args.id not in nodes:
        print(f"unknown node: {args.id}", file=sys.stderr)
        return 1
    adj: Dict[str, List[Tuple[str, str]]] = defaultdict(list)
    for nid, n in nodes.items():
        for l in n["meta"]["links"]:
            t, target = parse_link(l)
            adj[nid].append((target, t))
            adj[target].append((nid, f"{t} (in)"))
    seen, q = {args.id: 0}, deque([args.id])
    while q:  # BFS: O(V + E)
        cur = q.popleft()
        if seen[cur] >= args.depth:
            continue
        for nxt, t in adj[cur]:
            if nxt not in seen:
                seen[nxt] = seen[cur] + 1
                q.append(nxt)
                summ = nodes[nxt]["meta"].get("summary", "") if nxt in nodes else "(missing node)"
                print(f"{'  ' * seen[cur]}{cur} -[{t}]-> {nxt}: {summ}")
    return 0


# ------------------------------------------------------------------ upsert

def _split_csv(v: Optional[str]) -> Optional[List[str]]:
    return None if v is None else [x.strip() for x in v.split(",") if x.strip()]


def cmd_upsert(kg: KG, args) -> int:
    if not ID_RE.match(args.id):
        print("id must be lowercase kebab-case: <kind>-<slug>", file=sys.stderr)
        return 2
    path = os.path.join(kg.ndir, f"{args.id}.md")
    existing = parse_node(path) if os.path.exists(path) else None
    meta = dict(existing["meta"]) if existing else {"id": args.id}
    body = existing["body"] if existing else "## Facts\n- (add facts, each ending with → path:line)\n"
    if args.kind:
        meta["kind"] = args.kind
    for field in ("title", "summary"):
        if getattr(args, field) is not None:
            meta[field] = getattr(args, field).replace("\n", " ")
    for field in ("tags", "links", "sources"):
        v = _split_csv(getattr(args, field))
        if v is not None:
            meta[field] = v
    if "kind" not in meta or "summary" not in meta:
        print("new nodes need --kind and --summary", file=sys.stderr)
        return 2
    meta.setdefault("title", args.id.split("-", 1)[-1].replace("-", " ").title())
    meta["updated"] = today()
    meta["verified_commit"] = head_commit(kg.root)
    os.makedirs(kg.ndir, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(dump_node(meta, body))
    print(f"{'updated' if existing else 'created'} {os.path.relpath(path, kg.root)}")
    return 0


# ------------------------------------------------------------------ remove / prune

def remove_node(kg: KG, nid: str) -> List[str]:
    """Delete a node and drop links to it from other nodes. Returns the ids whose links changed."""
    os.remove(os.path.join(kg.ndir, f"{nid}.md"))
    touched = []
    for n in kg.load():
        links = [l for l in n["meta"]["links"] if parse_link(l)[1] != nid]
        if links != n["meta"]["links"]:
            n["meta"]["links"] = links
            with open(n["file"], "w", encoding="utf-8") as fh:
                fh.write(dump_node(n["meta"], n["body"]))
            touched.append(n["meta"].get("id", ""))
    return touched


def obsolete_nodes(kg: KG) -> List[str]:
    """Nodes whose every source path is gone: what they describe no longer exists."""
    out = []
    for n in kg.load():
        paths = [ps[0] for ps in (parse_source(s) for s in n["meta"]["sources"]) if ps]
        if paths and not any(os.path.exists(os.path.join(kg.root, p).rstrip("/")) for p in paths):
            out.append(n["meta"].get("id", ""))
    return out


def cmd_remove(kg: KG, args) -> int:
    if not os.path.exists(os.path.join(kg.ndir, f"{args.id}.md")):
        print(f"no node '{args.id}'", file=sys.stderr)
        return 2
    touched = remove_node(kg, args.id)
    cmd_index(kg, args)
    print(f"removed {args.id}" + (f"; dropped links in {', '.join(touched)}" if touched else ""))
    return 0


def cmd_prune(kg: KG, args) -> int:
    ids = obsolete_nodes(kg)
    if not ids:
        print("nothing to prune")
        return 0
    for nid in ids:
        if args.apply:
            remove_node(kg, nid)
        print(f"{'removed' if args.apply else 'obsolete'} {nid} (all sources gone)")
    if args.apply:
        cmd_index(kg, args)
    else:
        print("run `kg.py prune --apply` to remove them")
    return 0


# ------------------------------------------------------------------ validate

def validate(kg: KG) -> Tuple[List[str], List[str]]:
    errors, warnings = [], []
    nodes = kg.load()
    ids: Dict[str, str] = {}
    line_cache: Dict[str, int] = {}
    for n in nodes:
        m, rel = n["meta"], os.path.relpath(n["file"], kg.root)
        nid = m.get("id", "")
        for f in ("id", "kind", "summary"):
            if not m.get(f):
                errors.append(f"{rel}: missing '{f}'")
        if nid and not ID_RE.match(nid):
            errors.append(f"{rel}: id '{nid}' is not kebab-case")
        if nid and os.path.splitext(os.path.basename(n["file"]))[0] != nid:
            errors.append(f"{rel}: file name must equal id '{nid}'")
        if nid in ids:
            errors.append(f"{rel}: duplicate id '{nid}' (also {ids[nid]})")
        ids[nid] = rel
        if m.get("kind") and m["kind"] not in KINDS:
            warnings.append(f"{rel}: unknown kind '{m['kind']}'")
        if len(n["body"].splitlines()) > kg.max_node_lines:
            errors.append(f"{rel}: body has {len(n['body'].splitlines())} lines (max {kg.max_node_lines}); split the node")
        for src in m["sources"]:
            ps = parse_source(src)
            if not ps:
                errors.append(f"{rel}: bad source '{src}'")
                continue
            p, a, b = ps
            ap = os.path.join(kg.root, p)
            if not os.path.exists(ap.rstrip("/")):
                errors.append(f"{rel}: source missing '{p}'")
                continue
            if a and os.path.isfile(ap):
                if ap not in line_cache:
                    with open(ap, encoding="utf-8", errors="replace") as fh:
                        line_cache[ap] = sum(1 for _ in fh)
                if (b or a) > line_cache[ap]:
                    errors.append(f"{rel}: '{src}' is past end of file ({line_cache[ap]} lines)")
    for n in nodes:
        for l in n["meta"]["links"]:
            _, target = parse_link(l)
            if target not in ids:
                errors.append(f"{os.path.relpath(n['file'], kg.root)}: dangling link '{l}'")
    expected, _ = build_index(kg)
    try:
        with open(kg.index_path, encoding="utf-8") as fh:
            if fh.read() != expected:
                warnings.append("INDEX.md is out of date. Run `kg.py index`")
    except OSError:
        warnings.append("INDEX.md missing. Run `kg.py index`")
    return errors, warnings


def cmd_validate(kg: KG, args) -> int:
    errors, warnings = validate(kg)
    for w in warnings:
        print(f"WARN  {w}")
    for e in errors:
        print(f"ERROR {e}")
    print(f"{len(errors)} error(s), {len(warnings)} warning(s)")
    return 1 if errors else 0


# ------------------------------------------------------------------ stale / pending

def stale_nodes(kg: KG) -> List[Tuple[str, List[str]]]:
    nodes = kg.load()
    in_git = git(kg.root, "rev-parse", "--is-inside-work-tree") == "true"
    changed_since: Dict[str, Optional[set]] = {}
    out = []
    for n in nodes:
        m = n["meta"]
        files = [ps[0] for ps in (parse_source(s) for s in m["sources"]) if ps]
        if not files:
            continue
        commit = m.get("verified_commit") or "none"
        changed: List[str] = []
        if in_git and commit != "none":
            if commit not in changed_since:
                diff = git(kg.root, "diff", "--name-only", commit)
                changed_since[commit] = set(diff.splitlines()) if diff is not None else None
            cs = changed_since[commit]
            if cs is not None:
                changed = [f for f in files if f in cs or any(c.startswith(f.rstrip("/") + "/") for c in cs)]
        else:
            try:
                upd = _dt.datetime.fromisoformat(str(m.get("updated"))) + _dt.timedelta(days=1)
            except ValueError:
                upd = None
            for f in files:
                ap = os.path.join(kg.root, f)
                if upd and os.path.isfile(ap) and _dt.datetime.fromtimestamp(os.path.getmtime(ap)) > upd:
                    changed.append(f)
        if changed:
            out.append((m.get("id", ""), changed))
    return out


def cmd_stale(kg: KG, args) -> int:
    st = stale_nodes(kg)
    for nid, files in st:
        print(f"{nid}: sources changed → {', '.join(files[:5])}")
    if not st:
        print("no stale nodes")
    return 0


def read_pending(kg: KG) -> List[str]:
    try:
        with open(kg.pending_path, encoding="utf-8") as fh:
            items = [l.strip() for l in fh if l.strip()]
    except OSError:
        return []
    return sorted(set(items))


def is_ignored(kg: KG, rel: str) -> bool:
    return any(fnmatch.fnmatch(rel, g) or fnmatch.fnmatch(rel, g.replace("**/", "")) for g in kg.ignore)


def referencing(kg: KG) -> Dict[str, List[str]]:
    ref: Dict[str, List[str]] = defaultdict(list)
    for n in kg.load():
        for s in n["meta"]["sources"]:
            ps = parse_source(s)
            if ps:
                ref[ps[0].rstrip("/")].append(n["meta"].get("id", ""))
    return ref


def cmd_pending(kg: KG, args) -> int:
    if args.clear:
        # Truncate rather than delete: the Bash sandbox can refuse unlink inside .claude/.
        if os.path.exists(kg.pending_path):
            try:
                open(kg.pending_path, "w").close()
            except OSError as exc:
                print(f"could not clear {os.path.relpath(kg.pending_path, kg.root)}: {exc}", file=sys.stderr)
                return 1
        # The end-of-turn check counts its next batch from zero again (see hooks/kg_hooks.py).
        reported = os.path.join(os.path.dirname(kg.pending_path), "kg-reported.json")
        if os.path.exists(reported):
            try:
                open(reported, "w").close()
            except OSError:
                pass
        print("pending cleared")
        return 0
    items = [p for p in read_pending(kg) if not is_ignored(kg, p)]
    ref = referencing(kg)
    rows = []
    for p in items:
        ids = sorted(set(ref.get(p, []) + [i for d, v in ref.items() if p.startswith(d + "/") for i in v]))
        rows.append({"path": p, "nodes": ids})
    if args.json:
        print(json.dumps(rows, indent=1))
    else:
        for r in rows:
            print(f"{r['path']} → {', '.join(r['nodes']) if r['nodes'] else '(no node yet: new or uncovered)'}")
        if not rows:
            print("nothing pending")
    return 0


